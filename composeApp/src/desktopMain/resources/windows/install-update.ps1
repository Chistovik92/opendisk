# Установка обновления OpenDisk на Windows.
#
# Запускается самим приложением (UpdateInstaller) после того, как скачанный
# установщик сверен по контрольной сумме. Тот же файл гоняет CI на настоящей
# установке (scripts/verify-windows-install.ps1) — поэтому сценарий лежит
# отдельным файлом, а не строкой в коде: проверяется ровно то, что выполнится
# у пользователя.
#
# Установщик с 0.5.0 — это .exe (обёртка Burn поверх нашего MSI), а не MSI:
# msiexec тут не нужен, запускается сам установщик.
#
# /passive — только полоса прогресса, без вопросов: обновление человек уже
# подтвердил кнопкой в приложении. Работающую копию OpenDisk установщик
# закрывает сам (util:CloseApplication в Product.wxs).
#
# Запуск новой версии нужен именно здесь: галка «Запустить OpenDisk» живёт на
# последней странице установщика, а в сокращённом режиме этой страницы нет.
# Без явного запуска приложение после обновления просто исчезло бы с экрана.
# PowerShell, запускающий установщик, прав администратора не получает, поэтому
# и приложение стартует от имени пользователя, а не системы.

param(
    [Parameter(Mandatory = $true)][string]$Installer,
    [string]$Launcher
)

$ErrorActionPreference = 'Stop'

# Отказ в запросе прав (UAC) бросает исключение, и сценарий завершится с
# ненулевым кодом — приложение по нему поймёт, что установка не началась.
$process = Start-Process -FilePath $Installer -ArgumentList '/passive', '/norestart' -Verb RunAs -Wait -PassThru
$code = $process.ExitCode

# 3010 — «установлено, нужна перезагрузка». Для нас это тоже успех: файлы на
# месте, и приложение запускается.
if (($code -eq 0 -or $code -eq 3010) -and $Launcher -and (Test-Path -LiteralPath $Launcher)) {
    Start-Process -FilePath $Launcher
}

exit $code
